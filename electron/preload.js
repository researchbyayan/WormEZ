const {contextBridge,ipcRenderer,webUtils}=require('electron');
contextBridge.exposeInMainWorld('wormezDesktop',{
  downloadUpdate:()=>ipcRenderer.invoke('wormez:update-download'),
  installUpdate:()=>ipcRenderer.invoke('wormez:update-install'),
  onUpdate:fn=>{const l=(_e,v)=>fn(v);ipcRenderer.on('wormez:update',l);return()=>ipcRenderer.removeListener('wormez:update',l);},
  build:'1.3.0+20261112.beta-windows-editing',
  resourceCapacity:()=>ipcRenderer.invoke('wormez:resource-capacity'),
  setAnalysisActive:active=>ipcRenderer.send('wormez:analysis-active',!!active),
  trackingWorkerSource:()=>ipcRenderer.invoke('wormez:tracking-worker-source'),
  nativeVideoPath:file=>webUtils.getPathForFile(file),
  editVideo:(source,recipe)=>ipcRenderer.invoke('wormez:edit-video',{source,recipe}),
  cancelVideoEdit:()=>ipcRenderer.invoke('wormez:cancel-video-edit'),
  onVideoEditProgress:callback=>{const listener=(_event,value)=>callback(value);ipcRenderer.on('wormez:video-edit-progress',listener);return()=>ipcRenderer.removeListener('wormez:video-edit-progress',listener);},
  openVideo:()=>ipcRenderer.invoke('wormez:open-video'),
  openFolder:()=>ipcRenderer.invoke('wormez:open-folder'),
  saveFile:(suggestedName,data)=>ipcRenderer.invoke('wormez:save-file',{suggestedName,data}),
  beginCapture:mimeType=>ipcRenderer.invoke('wormez:capture-begin',{mimeType}),
  appendCapture:(id,data)=>ipcRenderer.invoke('wormez:capture-append',{id,data}),
  finishCapture:id=>ipcRenderer.invoke('wormez:capture-finish',{id}),
  cancelCapture:id=>ipcRenderer.invoke('wormez:capture-cancel',{id}),
  probeVideo:path=>ipcRenderer.invoke('wormez:probe-video',{path}),
  convertVideo:path=>ipcRenderer.invoke('wormez:convert-video',{path}),
  petriStatus:()=>ipcRenderer.invoke('wormez:petri-status'),
  petriDetect:body=>ipcRenderer.invoke('wormez:petri-detect',body),
  tapirStatus:()=>ipcRenderer.invoke('wormez:tapir-status'),
  tapirTrack:body=>ipcRenderer.invoke('wormez:tapir-track',body),
  windowState:()=>ipcRenderer.invoke('wormez:window-state'),
  setMaximized:on=>ipcRenderer.invoke('wormez:window-maximize',on),
  setScreensaverActive:active=>ipcRenderer.send('wormez:screensaver-active',!!active),
  onDismissScreensaver:callback=>{const listener=()=>callback();ipcRenderer.on('wormez:dismiss-screensaver',listener);return()=>ipcRenderer.removeListener('wormez:dismiss-screensaver',listener);},
  setTrueMaximize:on=>ipcRenderer.invoke('wormez:window-true-maximize',on)
});
